#!/usr/bin/env bash
#
# Build a lean, unattended Windows 11 ISO from a legally obtained source ISO.
# The script runs on NixOS (and other Linux/macOS systems with the same tools)
# and uses wimlib for WIM manipulation, so it does not need DISM or Windows.

set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
PROFILE="lean"
ISO=""
OUT=""
WORK="$SCRIPT_DIR/work"
INDEX=""
LOCALE="en-US"
INPUT_LOCALE=""
TIMEZONE="UTC"
USER_NAME="Admin"
PASSWORD=""
PASSWORD_SET=0
ALLOW_EMPTY_PASSWORD=0
GENERATED_PASSWORD=0
AUTOLOGON=0
PRODUCT_KEY=""
COMPUTER_NAME=""
UNATTEND=""
NO_UNATTEND=0
POSTINSTALL=1
REMOVE_WINRE=0
SOLID=0
EXPERIMENTAL=0
KEEP_WORK=0
FORCE=0
SEVEN_Z=""

usage() {
    cat <<'USAGE'
Build a lean Windows 11 ISO from a source ISO.

Usage:
  ./build-win11.sh --iso /path/to/Win11.iso [options]

Required:
  -i, --iso PATH             Source Windows 11 ISO (x64).

Options:
  -p, --profile NAME         safe | lean | micro (default: lean)
  -o, --out PATH             Output ISO (default: windows/out/Win11-<profile>-<date>.iso)
  -w, --workdir PATH         Working directory (default: windows/work)
      --index N              Image index to apply. Default: auto-detect Windows 11 Pro.
      --locale NAME          Setup locale (default: en-US; e.g. de-DE)
      --input-locale VALUE   Input locale, e.g. 0407:00000407
      --timezone NAME        Windows time zone ID (default: UTC)
      --user NAME            Local administrator name (default: Admin)
      --password VALUE       Local account password. A random one is generated by default.
      --allow-empty-password Explicitly allow a blank local password (not recommended).
      --autologon            Enable one auto-logon for the local account (lab use only).
      --product-key KEY      Optional product key for unattended edition selection.
      --computer-name NAME   Optional computer name.
      --unattend PATH        Use an existing autounattend.xml instead of the generated one.
      --no-unattend          Do not add autounattend.xml (not recommended).
      --no-postinstall       Do not add the first-boot debloat script.
      --remove-winre         Remove Windows Recovery Environment from the image.
      --solid                Convert install.wim to solid compression (smaller, slower).
      --experimental         Required for the micro profile.
      --keep-work            Keep the extracted ISO and mounted image after success.
      --force                Overwrite an existing output file.
  -h, --help                 Show this help.

Profiles:
  safe   Unattended setup, cache cleanup and WIM recompression. No app removal.
  lean   safe + first-boot removal of consumer AppX and telemetry policies.
         Store, Defender and Windows Update stay available.
  micro  lean + Store, Xbox, OneDrive, search index, SysMain and optional WinRE.
         Experimental; test in a VM before using it on hardware.

Examples:
  ./build-win11.sh --iso ~/Downloads/Win11_24H2.iso --profile lean
  ./build-win11.sh --iso ~/Downloads/Win11_24H2.iso --profile micro \
      --experimental --solid --remove-winre --locale de-DE
USAGE
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

log() {
    printf '\n==> %s\n' "$*"
}

warn() {
    printf 'warning: %s\n' "$*" >&2
}

need_cmd() {
    command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        -i|--iso) ISO="${2:-}"; shift 2 ;;
        -p|--profile) PROFILE="${2:-}"; shift 2 ;;
        -o|--out|--output) OUT="${2:-}"; shift 2 ;;
        -w|--workdir) WORK="${2:-}"; shift 2 ;;
        --index) INDEX="${2:-}"; shift 2 ;;
        --locale) LOCALE="${2:-}"; shift 2 ;;
        --input-locale) INPUT_LOCALE="${2:-}"; shift 2 ;;
        --timezone) TIMEZONE="${2:-}"; shift 2 ;;
        --user) USER_NAME="${2:-}"; shift 2 ;;
        --password) PASSWORD="${2:-}"; PASSWORD_SET=1; shift 2 ;;
        --allow-empty-password) ALLOW_EMPTY_PASSWORD=1; shift ;;
        --autologon) AUTOLOGON=1; shift ;;
        --product-key) PRODUCT_KEY="${2:-}"; shift 2 ;;
        --computer-name) COMPUTER_NAME="${2:-}"; shift 2 ;;
        --unattend) UNATTEND="${2:-}"; shift 2 ;;
        --no-unattend) NO_UNATTEND=1; shift ;;
        --no-postinstall) POSTINSTALL=0; shift ;;
        --remove-winre) REMOVE_WINRE=1; shift ;;
        --solid) SOLID=1; shift ;;
        --experimental) EXPERIMENTAL=1; shift ;;
        --keep-work) KEEP_WORK=1; shift ;;
        --force) FORCE=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown option: $1 (try --help)" ;;
    esac
done

[[ -n "$ISO" ]] || die "--iso is required (try --help)"
[[ -f "$ISO" ]] || die "source ISO not found: $ISO"
case "$PROFILE" in
    safe|lean|micro) ;;
    *) die "invalid profile: $PROFILE (use safe, lean or micro)" ;;
esac
if [[ "$PROFILE" == "micro" && "$EXPERIMENTAL" -eq 0 ]]; then
    die "the micro profile is experimental; re-run with --experimental after reading the warnings"
fi
if [[ "$PROFILE" == "safe" && "$POSTINSTALL" -eq 1 ]]; then
    POSTINSTALL=0
fi

if command -v 7z >/dev/null 2>&1; then
    SEVEN_Z="7z"
elif command -v 7zz >/dev/null 2>&1; then
    SEVEN_Z="7zz"
else
    die "required command not found: 7z (or 7zz). Install p7zip / 7zip."
fi

need_cmd wimlib-imagex
need_cmd xorriso
need_cmd python3
need_cmd find

if [[ -z "$PASSWORD" ]]; then
    if [[ "$PASSWORD_SET" -eq 1 && "$ALLOW_EMPTY_PASSWORD" -eq 0 ]]; then
        die "an empty password was supplied; pass --allow-empty-password if you really mean it"
    fi
    if [[ "$ALLOW_EMPTY_PASSWORD" -eq 0 ]]; then
        PASSWORD="$(python3 -c 'import secrets; print(secrets.token_urlsafe(15))')"
        GENERATED_PASSWORD=1
    fi
fi
if [[ "$AUTOLOGON" -eq 1 && -z "$PASSWORD" ]]; then
    warn "auto-logon is enabled with an empty password; use this only in a disposable lab VM"
fi

if [[ -z "$OUT" ]]; then
    OUT="$SCRIPT_DIR/out/Win11-${PROFILE}-$(date +%Y%m%d-%H%M).iso"
fi
mkdir -p "$(dirname "$OUT")"
OUT="$(cd -- "$(dirname "$OUT")" && pwd)/$(basename "$OUT")"
if [[ -e "$OUT" && "$FORCE" -eq 0 ]]; then
    die "output already exists: $OUT (use --force to overwrite)"
fi

mkdir -p "$WORK"
WORK="$(cd -- "$WORK" && pwd)"
case "$WORK" in
    /|"$HOME"|"$SCRIPT_DIR"|"$REPO_ROOT")
        die "refusing to use a broad directory as --workdir: $WORK"
        ;;
esac
EXTRACT="$WORK/extracted"
ROOT="$WORK/root"
SOURCES="$EXTRACT/sources"

cleanup() {
    local status=$?
    trap - EXIT
    if [[ "$status" -ne 0 ]]; then
        warn "build failed; work directory kept at $WORK"
    elif [[ "$KEEP_WORK" -eq 0 && "$OUT" != "$WORK"/* ]]; then
        rm -rf "$WORK"
    else
        log "work directory kept at $WORK"
    fi
    exit "$status"
}
trap cleanup EXIT

log "Preparing work directory: $WORK"
rm -rf "$EXTRACT" "$ROOT"
mkdir -p "$EXTRACT" "$ROOT"

log "Extracting source ISO: $ISO"
"$SEVEN_Z" x -y -o"$EXTRACT" "$ISO" >/dev/null

WIM="$SOURCES/install.wim"
ESD="$SOURCES/install.esd"
if [[ ! -f "$WIM" && -f "$ESD" ]]; then
    log "Converting install.esd to install.wim (this can take a while)"
    wimlib-imagex export "$ESD" all "$WIM" --compress=LZX
elif [[ ! -f "$WIM" ]]; then
    if compgen -G "$SOURCES/install*.swm" >/dev/null; then
        die "split install*.swm images are not supported; merge them with wimlib-imagex join first"
    fi
    die "install.wim / install.esd not found under $SOURCES"
fi
[[ -f "$WIM" ]] || die "install.wim is missing"
chmod u+w "$WIM"

log "Images in install.wim"
wimlib-imagex info "$WIM" | awk '/^Index:[[:space:]]/ || /^Name:[[:space:]]/ {print}'

if [[ -z "$INDEX" ]]; then
    INDEX="$(wimlib-imagex info "$WIM" | awk '
        /^Index:[[:space:]]/ { idx = $2 }
        /^Name:[[:space:]]/ {
            name = $0
            sub(/^Name:[[:space:]]*/, "", name)
            if (name ~ /^Windows 11 Pro($| )/) { print idx; exit }
        }
    ')"
    [[ -n "$INDEX" ]] || die "could not auto-detect Windows 11 Pro; pass --index N"
fi

wimlib-imagex info "$WIM" "$INDEX" >/dev/null 2>&1 || die "image index $INDEX does not exist"
EDITION="$(wimlib-imagex info "$WIM" "$INDEX" | awk -F': *' '/^Name:/ {print $2; exit}')"
[[ -n "$EDITION" ]] || EDITION="Windows 11"
log "Selected image $INDEX: $EDITION"

log "Applying image to $ROOT"
wimlib-imagex apply "$WIM" "$INDEX" "$ROOT"

clean_dir() {
    local dir="$1"
    if [[ -d "$dir" ]]; then
        find "$dir" -mindepth 1 -delete 2>/dev/null || true
    fi
}

log "Removing setup caches, logs and temporary files from the image"
clean_dir "$ROOT/Windows/SoftwareDistribution/Download"
clean_dir "$ROOT/Windows/Temp"
clean_dir "$ROOT/Windows/Prefetch"
clean_dir "$ROOT/Windows/Logs"
clean_dir "$ROOT/Windows/System32/LogFiles"
clean_dir "$ROOT/Windows/System32/winevt/Logs"
clean_dir "$ROOT/ProgramData/Microsoft/Windows/WER/ReportQueue"
clean_dir "$ROOT/ProgramData/Microsoft/Windows/WER/ReportArchive"

if [[ "$REMOVE_WINRE" -eq 1 ]]; then
    log "Removing Windows Recovery Environment (WinRE)"
    rm -rf "$ROOT/Windows/System32/Recovery"
fi

if [[ "$POSTINSTALL" -eq 1 && "$PROFILE" != "safe" ]]; then
    log "Adding first-boot debloat scripts (profile: $PROFILE)"
    SCRIPTS="$EXTRACT/sources/\$OEM\$/\$\$/Setup/Scripts"
    mkdir -p "$SCRIPTS"
    cp "$SCRIPT_DIR/scripts/SetupComplete.ps1" "$SCRIPTS/SetupComplete.ps1"
    sed "s/@@PROFILE@@/$PROFILE/g" \
        "$SCRIPT_DIR/templates/SetupComplete.cmd.in" > "$SCRIPTS/SetupComplete.cmd"
fi

if [[ "$NO_UNATTEND" -eq 0 ]]; then
    if [[ -n "$UNATTEND" ]]; then
        [[ -f "$UNATTEND" ]] || die "unattend file not found: $UNATTEND"
        log "Using custom autounattend.xml: $UNATTEND"
        cp "$UNATTEND" "$EXTRACT/autounattend.xml"
    else
        log "Rendering autounattend.xml"
        RENDER_ARGS=(
            --template "$SCRIPT_DIR/templates/autounattend.xml.in"
            --output "$EXTRACT/autounattend.xml"
            --locale "$LOCALE"
            --input-locale "$INPUT_LOCALE"
            --timezone "$TIMEZONE"
            --user "$USER_NAME"
            --password "$PASSWORD"
            --index 1
            --product-key "$PRODUCT_KEY"
            --computer-name "$COMPUTER_NAME"
        )
        if [[ "$AUTOLOGON" -eq 1 ]]; then
            RENDER_ARGS+=(--autologon)
        fi
        python3 "$SCRIPT_DIR/render-unattend.py" "${RENDER_ARGS[@]}"
    fi
else
    warn "autounattend.xml disabled; Windows Setup will show the normal interactive screens"
fi

NEW_WIM="$WORK/install.wim"
log "Capturing modified image with LZX compression"
wimlib-imagex capture "$ROOT" "$NEW_WIM" "$EDITION (slim)" --compress=LZX

log "Replacing install.wim in the ISO tree"
rm -f "$SOURCES/install.esd" "$SOURCES/install.swm" "$SOURCES/install2.swm"
mv "$NEW_WIM" "$SOURCES/install.wim"
chmod 644 "$SOURCES/install.wim"

if [[ "$SOLID" -eq 1 ]]; then
    log "Applying solid compression (this is the slow part)"
    wimlib-imagex optimize "$SOURCES/install.wim" --solid
fi

log "Verifying WIM"
wimlib-imagex verify "$SOURCES/install.wim" >/dev/null

BIOS_BOOT="boot/etfsboot.com"
EFI_BOOT="efi/microsoft/boot/efisys.bin"
[[ -f "$EXTRACT/$BIOS_BOOT" ]] || die "BIOS boot image not found: $BIOS_BOOT"
if [[ ! -f "$EXTRACT/$EFI_BOOT" ]]; then
    EFI_BOOT="efi/microsoft/boot/efisys_noprompt.bin"
fi
[[ -f "$EXTRACT/$EFI_BOOT" ]] || die "UEFI boot image not found under efi/microsoft/boot"

VOLID="WIN11_SLIM"
if [[ "$PROFILE" == "micro" ]]; then
    VOLID="WIN11_MICRO"
fi

log "Building bootable ISO: $OUT"
xorriso -as mkisofs \
    -iso-level 3 \
    -full-iso9660-filenames \
    -J -joliet-long \
    -relaxed-filenames \
    -volid "$VOLID" \
    -eltorito-boot "$BIOS_BOOT" \
    -eltorito-catalog boot/boot.cat \
    -no-emul-boot \
    -boot-load-size 8 \
    -boot-info-table \
    -eltorito-alt-boot \
    -eltorito-platform efi \
    -e "$EFI_BOOT" \
    -no-emul-boot \
    -boot-load-size 1 \
    -isohybrid-gpt-basdat \
    -o "$OUT" \
    "$EXTRACT"

log "Writing SHA-256 checksum"
if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$OUT" > "$OUT.sha256"
else
    shasum -a 256 "$OUT" > "$OUT.sha256"
fi

SIZE="$(du -h "$OUT" | awk '{print $1}')"
log "Done"
cat <<EOF
Output:   $OUT
Size:     $SIZE
Profile:  $PROFILE
Edition:  $EDITION
Checksum: $OUT.sha256
EOF

if [[ "$GENERATED_PASSWORD" -eq 1 ]]; then
    printf 'Local password (store it now): %s\n' "$PASSWORD"
elif [[ -z "$PASSWORD" ]]; then
    printf 'Local password: <empty> (explicitly allowed)\n'
fi

if [[ "$PROFILE" == "micro" ]]; then
    warn "micro is unsupported and removes Store/search/OneDrive; keep a recovery image and test in a VM"
fi
warn "Windows is licensed software. Do not redistribute the modified ISO."
