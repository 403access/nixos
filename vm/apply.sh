#!/usr/bin/env bash
# Sync this repository into a NixOS machine and rebuild it.
# See ./README.md; `./vm.sh up` runs this plus machine creation/startup.
#
# DESKTOP_PROFILE=xfce|rice|plasma|hyprland overrides the desktop profile
# for this rebuild (and is remembered in /etc/nixos/vm/desktop.nix).
set -euo pipefail

MACHINE="${ORB_MACHINE:-control-test}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="${DESKTOP_PROFILE:-}"

case "$PROFILE" in
  ""|xfce|rice|plasma|hyprland) ;;
  *)
    echo "Unknown desktop profile '$PROFILE' (use xfce, rice, plasma, or hyprland)." >&2
    exit 1
    ;;
esac

if ! orb list -q | grep -qx "$MACHINE"; then
  echo "Creating NixOS machine '$MACHINE'..."
  orb create --cpus 4 --memory 6G --disk 40G nixos:25.11 "$MACHINE"
fi

write_profile() {
  orb -m "$MACHINE" sudo tee /etc/nixos/vm/desktop.nix >/dev/null <<NIX
# Generated by vm/apply.sh.
{ ... }:

{
  myDesktop.profile = "$1";
}
NIX
}

echo "Syncing configuration into /etc/nixos..."
orb -m "$MACHINE" sudo mkdir -p /etc/nixos/vm /etc/nixos/desktop
orb -m "$MACHINE" sudo rm -rf /etc/nixos/server
orb -m "$MACHINE" sudo mkdir -p /etc/nixos/server
orb -m "$MACHINE" sudo cp "$ROOT/server/Cargo.toml" "$ROOT/server/Cargo.lock" /etc/nixos/server/
orb -m "$MACHINE" sudo cp -r "$ROOT/server/src" "$ROOT/server/tests" /etc/nixos/server/
orb -m "$MACHINE" sudo cp "$ROOT/nixos-control.nix" /etc/nixos/
orb -m "$MACHINE" sudo cp -rT "$ROOT/desktop" /etc/nixos/desktop
orb -m "$MACHINE" sudo cp "$ROOT/vm/configuration.nix" /etc/nixos/vm/configuration.nix

if [[ -n "$PROFILE" ]]; then
  write_profile "$PROFILE"
elif ! orb -m "$MACHINE" test -f /etc/nixos/vm/desktop.nix; then
  write_profile rice
fi

orb -m "$MACHINE" sudo tee /etc/nixos/control-test.nix >/dev/null <<'NIX'
# Generated by vm/apply.sh: keep OrbStack's own configuration (networking,
# users, container boot) and add the NixOS Control test module on top.
{ ... }:

{
  imports = [
    ./configuration.nix
    ./vm/configuration.nix
    ./vm/desktop.nix
  ];
}
NIX

echo "Rebuilding..."
orb -m "$MACHINE" sudo nixos-rebuild switch -I nixos-config=/etc/nixos/control-test.nix

# The module deliberately sets restartIfChanged = false, so pick up a new
# server binary explicitly.
orb -m "$MACHINE" sudo systemctl restart nixos-control

# Restart the VNC session so changes to the declarative dotfiles take effect
# even when the session command itself did not change.
orb -m "$MACHINE" sudo systemctl restart vnc-session 2>/dev/null || true
